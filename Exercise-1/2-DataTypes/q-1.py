# 1. Demonstrate int, float, str, bool, and complex.

# int (Integer)
age = 20;
print("\n", age);
print(type(age));

# float (Decimal number)
price = 99.99;
print("\n", price);
print(type(price));

# str (String)
name = "John";
print("\n", name);
print(type(name));

# bool (Boolean)
is_student = True;
print("\n", is_student);
print(type(is_student));

# complex (Complex number)
number = 3 + 4j;
print("\n", number);
print(type(number));

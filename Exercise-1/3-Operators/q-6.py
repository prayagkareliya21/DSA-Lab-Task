# 6. Demonstrate assignment operators (+=, -=, *=, /=).
num = int(input("\nEnter a number: "));

# Addison
num += 5;
print("\nAfter += 5:", num);

#  Subtraction
num -= 2;
print("After -= 2:", num);

# Multiplication
num *= 3;
print("After *= 3:", num);

# Division
num /= 2;
print("After /= 2:", num);

# 4. Compare two numbers using relational operators. 

num1 = int(input("\nEnter first number: "));
num2 = int(input("Enter second number: "));

print("\nnum1 == num2:", num1 == num2);
print("num1 != num2:", num1 != num2);
print("num1 > num2:", num1 > num2);
print("num1 < num2:", num1 < num2);
print("num1 >= num2:", num1 >= num2);
print("num1 <= num2:", num1 <= num2);
